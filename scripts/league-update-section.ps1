# Regenerate the "all checkpoints" recheck section of PerformanceLeague.md from a bench-league-recheck.ps1 results file.
# The section sits between the markers  <!-- league-recheck-all:begin -->  and  <!-- league-recheck-all:end -->  (created before the
# "## Text encoders" heading on first use), so re-running after a longer run simply replaces it. Older rows are left untouched as dated history.
# Usage: pwsh scripts/league-update-section.ps1 -Results <results.md> [-Date 2026-10-11] [-Partial "84 of 103 models"]
param(
    [Parameter(Mandatory)][string]$Results,
    [string]$Date = (Get-Date -Format 'yyyy-MM-dd'),
    [string]$Partial = '',
    [string]$League = (Join-Path (Split-Path -Parent $PSScriptRoot) 'PerformanceLeague.md')
)
$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot
$tmpCsv = [System.IO.Path]::GetTempFileName()
& (Join-Path $PSScriptRoot 'league-compare.ps1') -Results $Results -League $League -Csv $tmpCsv | Out-Null
$cmp = @(Import-Csv $tmpCsv)
Remove-Item $tmpCsv -ErrorAction SilentlyContinue

$res = @(Get-Content $Results | Where-Object { $_ -match '^\| .+? \| [\d.]+ \| .*? \| (cpu|vulkan) \| 500 \|' })
$meas = @($res | Where-Object { $_ -match '\| (cpu|vulkan) \| 500 \| \d' })
$uns = @($res | Where-Object { $_ -match 'UNSUPPORTED' })
$tmo = @($res | Where-Object { $_ -match 'TIMEOUT' })
$models = @($res | ForEach-Object { ($_ -split '\|')[1].Trim() } | Select-Object -Unique)
$commit = ((Get-Content $Results | Where-Object { $_ -match 'Commit `' } | Select-Object -First 1) -replace '.*Commit `([^`]+)`.*', '$1')

$faster = @($cmp | Where-Object { [double]$_.change -ge 1.10 }).Count
$flat = @($cmp | Where-Object { [double]$_.change -lt 1.10 -and [double]$_.change -ge 0.90 }).Count
$slower = @($cmp | Where-Object { [double]$_.change -lt 0.90 })

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('<!-- league-recheck-all:begin -->')
[void]$sb.AppendLine("## Our-side recheck, every text-generation checkpoint, $Date (C# only)")
[void]$sb.AppendLine()
if ($Partial) { [void]$sb.AppendLine("> **Partial run: $Partial.** This section is regenerated by ``scripts/league-update-section.ps1`` when the run completes.`n") }
[void]$sb.AppendLine("Every text-generation GGUF under every drive's ``_models`` (plus ``K:\_other_models`` and the repo's ``models/``), de-duplicated, smallest first, from ``scripts/bench-league-recheck.ps1 -Set all`` (commit ``$commit``, engine defaults, **one run per row, so treat a single-digit-percent difference as noise**). Prompt: ``docs/reference/benchmark-prompt.txt`` (about 490-580 tokens), 16 new tokens: the prefill column is prompt processing at that length, the decode column is decode after that prompt. CPU is ``-g 0``, Vulkan is ``-g -1``. Same machine as the rest of this file (Ryzen 7 5700G, 63 GB, integrated Radeon), so rule 13 applies. $($models.Count) models, $($meas.Count) measured rows, $($uns.Count) unsupported rows, $($tmo.Count) timeouts.")
[void]$sb.AppendLine()
[void]$sb.AppendLine("**No C++ reference was re-measured, so there are no ratios here.** Checkpoints that are not text-generation models (embeddings, ASR, TTS, diffusion, vision projectors) and the unsupported ones are listed in [docs/2-coverage/2026-10-11-checkpoints-not-supported-yet.md](docs/2-coverage/2026-10-11-checkpoints-not-supported-yet.md).")
[void]$sb.AppendLine()
[void]$sb.AppendLine("### Change against the older rows in this file")
[void]$sb.AppendLine()
[void]$sb.AppendLine("$($cmp.Count) metric rows over $(@($cmp | Select-Object -ExpandProperty model -Unique).Count) models have an older C# row in this file with a 400-650 token prompt on the same backend. **$faster are at least 10% faster, $flat are within 10%, $($slower.Count) are at least 10% slower.** The large Vulkan prefill gains are the Path 3 tiled matmul, the causal GQA prefill attention and (for Gemma 4) the CPU-prefill handoff; the Vulkan decode gains are the GQA split-KV attention and the mat-vec kernels. CPU changes are not attributed to anything in this session. Prompt lengths differ between old and new rows by up to about 100 tokens where noted in the token columns.")
[void]$sb.AppendLine()
if ($slower.Count -gt 0) {
    [void]$sb.AppendLine("**Slower than the older row (single run each, so confirm before acting; a re-run with 3 runs is the next step):**")
    [void]$sb.AppendLine()
    [void]$sb.AppendLine('| Model | Backend | Metric | Old tok | New tok | Old t/s | Old date | New t/s | New/old |')
    [void]$sb.AppendLine('|---|---|---|---:|---:|---:|---|---:|---:|')
    foreach ($r in ($slower | Sort-Object { [double]$_.change })) { [void]$sb.AppendLine("| $($r.model) | $($r.backend) | $($r.metric) | $($r.oldTok) | $($r.newTok) | $($r.old) | $($r.oldDate) | $($r.new) | $($r.change)x |") }
    [void]$sb.AppendLine()
}
[void]$sb.AppendLine("**Full comparison (new / old), largest gain first:**")
[void]$sb.AppendLine()
[void]$sb.AppendLine('| Model | Backend | Metric | Old tok | New tok | Old t/s | Old date | New t/s | New/old |')
[void]$sb.AppendLine('|---|---|---|---:|---:|---:|---|---:|---:|')
foreach ($r in ($cmp | Sort-Object { [double]$_.change } -Descending)) { [void]$sb.AppendLine("| $($r.model) | $($r.backend) | $($r.metric) | $($r.oldTok) | $($r.newTok) | $($r.old) | $($r.oldDate) | $($r.new) | $($r.change)x |") }
[void]$sb.AppendLine()
[void]$sb.AppendLine("### All measured rows")
[void]$sb.AppendLine()
[void]$sb.AppendLine('| Model | GB | Arch | Backend | Prompt tok | Prefill t/s | Decode t/s |')
[void]$sb.AppendLine('|---|---:|---|---|---:|---:|---:|')
foreach ($l in $meas) {
    $c = ($l -split '\|') | ForEach-Object { $_.Trim() }
    [void]$sb.AppendLine("| $($c[1]) | $($c[2]) | $($c[3]) | $($c[4]) | $($c[6]) | $($c[7]) | $($c[8]) |")
}
[void]$sb.AppendLine()
[void]$sb.AppendLine("Performance Check: $Date for every row above.")
[void]$sb.AppendLine()
[void]$sb.AppendLine('---')
[void]$sb.AppendLine('<!-- league-recheck-all:end -->')

$text = Get-Content -Raw -Path $League
$new = $sb.ToString()
if ($text -match '(?s)<!-- league-recheck-all:begin -->.*?<!-- league-recheck-all:end -->\r?\n?') {
    $text = [regex]::Replace($text, '(?s)<!-- league-recheck-all:begin -->.*?<!-- league-recheck-all:end -->\r?\n?', [System.Text.RegularExpressions.MatchEvaluator] { param($m) $new })
} else {
    $idx = $text.IndexOf('## Text encoders (embeddings / rerank), vs ONNX Runtime')
    if ($idx -lt 0) { throw 'anchor heading not found' }
    $text = $text.Substring(0, $idx) + $new + "`n" + $text.Substring($idx)
}
Set-Content -Path $League -Value $text -Encoding utf8 -NoNewline
"updated $League : $($cmp.Count) comparison rows, $($meas.Count) measured rows, $($slower.Count) slower"
