# Write docs/2-coverage/2026-10-11-checkpoints-not-supported-yet.md from a bench-league-recheck.ps1 results file (and the checkpoint inventory).
# Re-run after a longer / later recheck to refresh it. Usage: pwsh scripts/league-unsupported-doc.ps1 -Results <results.md> [-Partial "84 of 103 models"]
param(
    [Parameter(Mandatory)][string]$Results,
    [string]$Partial = '',
    [string]$Date = (Get-Date -Format 'yyyy-MM-dd'),
    [string]$Out = ''
)
$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot
if (-not $Out) { $Out = Join-Path $repo 'docs/2-coverage/2026-10-11-checkpoints-not-supported-yet.md' }

$lines = @(Get-Content $Results | Where-Object { $_ -match '^\| .+? \| [\d.]+ \| .*? \| (cpu|vulkan) \| 500 \|' })
$rows = foreach ($l in $lines) {
    $c = ($l -split '(?<!\\)\|') | ForEach-Object { $_.Trim() }
    [pscustomobject]@{ model = $c[1]; gb = $c[2]; arch = $c[3]; backend = $c[4]; prefill = $c[7]; decode = $c[8]; note = $c[9] }
}
$byModel = $rows | Group-Object model
$cpuOk = @{}; foreach ($r in $rows) { if ($r.backend -eq 'cpu' -and $r.prefill -match '^\d') { $cpuOk[$r.model] = "$($r.prefill) / $($r.decode)" } }
$vkOk = @{}; foreach ($r in $rows) { if ($r.backend -eq 'vulkan' -and $r.prefill -match '^\d') { $vkOk[$r.model] = "$($r.prefill) / $($r.decode)" } }

function Cause([string]$note) {
    switch -Regex ($note) {
        'not admitted'                                   { return 'architecture is ported but deliberately not admitted (see the exception text)' }
        'Missing tensor: blk\.0\.attn_q'                 { return 'fails with "Missing tensor: blk.0.attn_q.weight": the Vulkan full-offload pass assumes standard attention in every layer (inferred: this architecture has a hybrid, recurrent or MLA layer 0; not yet traced)' }
        'Missing tensor: blk\.0\.attn_k'                 { return 'fails with "Missing tensor: blk.0.attn_k.weight" (inferred: MLA attention stores K differently; not yet traced)' }
        'Missing tensor: blk\.0\.attn_norm'              { return 'fails with "Missing tensor: blk.0.attn_norm.weight" (inferred: this architecture has no attn_norm weight, e.g. non-parametric or post-norm layout; not yet traced)' }
        'PRISM|PTQ1_0|PQ2_0'                             { return 'PRISM (PQ2_0 / PTQ1_0 + Hadamard) weights are implemented only on the CPU hybrid-GDN pass' }
        default                                          { return $note }
    }
}

$unsup = @($rows | Where-Object { $_.prefill -eq 'UNSUPPORTED' })
$timeout = @($rows | Where-Object { $_.prefill -eq 'TIMEOUT' })
$bothFail = @($unsup | Group-Object model | Where-Object { @($_.Group | Where-Object backend -eq 'cpu').Count -gt 0 -and @($_.Group | Where-Object backend -eq 'vulkan').Count -gt 0 })
$vulkanOnly = @($unsup | Where-Object backend -eq 'vulkan' | Where-Object { $cpuOk.ContainsKey($_.model) })
$cpuOnlyFail = @($unsup | Where-Object backend -eq 'cpu' | Where-Object { $vkOk.ContainsKey($_.model) })

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine("# Checkpoints we do not support yet ($Date)")
[void]$sb.AppendLine()
[void]$sb.AppendLine('Source: `scripts/bench-league-recheck.ps1 -Set all` over every text-generation GGUF found on every drive (inventory: `scripts/list-checkpoints.ps1`). Each checkpoint was run once on the CPU path (`-g 0`) and once on the Vulkan full-offload path (`-g -1`) with a ~500-token prompt. A row below means the engine **could not produce a result**, which is different from "slow": slow checkpoints are in `PerformanceLeague.md`.')
[void]$sb.AppendLine()
if ($Partial) { [void]$sb.AppendLine("> **Partial run: $Partial.** Regenerated by ``scripts/league-unsupported-doc.ps1`` when the run completes.`n") }
[void]$sb.AppendLine("Counts at generation: $(@($byModel).Count) models attempted, $(@($unsup | Select-Object -ExpandProperty model -Unique).Count) with at least one unsupported backend, $($timeout.Count) timeouts.")
[void]$sb.AppendLine()
[void]$sb.AppendLine('## 1. Fails on both CPU and Vulkan')
[void]$sb.AppendLine()
if ($bothFail.Count -eq 0) { [void]$sb.AppendLine('None in this run.') } else {
    [void]$sb.AppendLine('| Checkpoint | GB | Architecture | Why |'); [void]$sb.AppendLine('|---|---:|---|---|')
    foreach ($g in $bothFail) { $r = $g.Group | Select-Object -First 1; $why = Cause (($g.Group | Where-Object backend -eq 'vulkan' | Select-Object -First 1).note); [void]$sb.AppendLine("| $($g.Name) | $($r.gb) | $($r.arch) | $why |") }
}
[void]$sb.AppendLine()
[void]$sb.AppendLine('## 2. Runs on CPU, fails on Vulkan full offload (`-g -1`)')
[void]$sb.AppendLine()
[void]$sb.AppendLine('These checkpoints work today with the default CPU path; only `-g -1` fails, so the user-visible limit is "CPU only". CPU figure is prefill / decode tok/s at ~500 tokens.')
[void]$sb.AppendLine()
if ($vulkanOnly.Count -eq 0) { [void]$sb.AppendLine('None in this run.') } else {
    [void]$sb.AppendLine('| Checkpoint | GB | Architecture | CPU prefill / decode | Why Vulkan fails |'); [void]$sb.AppendLine('|---|---:|---|---|---|')
    foreach ($r in $vulkanOnly) { [void]$sb.AppendLine("| $($r.model) | $($r.gb) | $($r.arch) | $($cpuOk[$r.model]) | $(Cause $r.note) |") }
}
[void]$sb.AppendLine()
[void]$sb.AppendLine('## 3. Runs on Vulkan, fails on CPU')
[void]$sb.AppendLine()
if ($cpuOnlyFail.Count -eq 0) { [void]$sb.AppendLine('None in this run.') } else {
    [void]$sb.AppendLine('| Checkpoint | GB | Architecture | Vulkan prefill / decode | Why CPU fails |'); [void]$sb.AppendLine('|---|---:|---|---|---|')
    foreach ($r in $cpuOnlyFail) { [void]$sb.AppendLine("| $($r.model) | $($r.gb) | $($r.arch) | $($vkOk[$r.model]) | $(Cause $r.note) |") }
}
[void]$sb.AppendLine()
[void]$sb.AppendLine('## 4. Timeouts')
[void]$sb.AppendLine()
if ($timeout.Count -eq 0) { [void]$sb.AppendLine('None in this run.') } else {
    [void]$sb.AppendLine('| Checkpoint | GB | Architecture | Backend | Note |'); [void]$sb.AppendLine('|---|---:|---|---|---|')
    foreach ($r in $timeout) { [void]$sb.AppendLine("| $($r.model) | $($r.gb) | $($r.arch) | $($r.backend) | $($r.note) |") }
}
[void]$sb.AppendLine()
[void]$sb.AppendLine('## 5. Not tested by this harness (not "unsupported")')
[void]$sb.AppendLine()
[void]$sb.AppendLine('Embeddings / rerank, ASR, TTS, vocoders, diffusion, vision projectors (`mmproj`) and non-GGUF checkpoints are not text-generation models, so the text CLI cannot time them. They have their own harnesses (`scripts/bench-audio.ps1`, `scripts/bench-image.ps1`, the encoder benchmark tests) and their own rows in [STATUS.md](../STATUS.md). Their inventory is at the end of the results file this document was generated from; it is not repeated here because "not covered by this run" says nothing about whether they work.')
[void]$sb.AppendLine()
[void]$sb.AppendLine('## What to do with this list')
[void]$sb.AppendLine()
[void]$sb.AppendLine('- Section 2 is the cheapest to shrink: each cause above is one tensor-naming or layer-layout assumption in the Vulkan full-offload pass (`GpuForwardPass`) or a missing hybrid GPU path, not a missing architecture. `stingray scout` (rule 15) is the first step for any of them.')
[void]$sb.AppendLine('- Section 1 entries are known architecture ports that are deliberately not admitted; promotion follows the normal admission path (a real checkpoint, an independent reference, timed runs, then the STATUS row).')
[void]$sb.AppendLine('- Re-run `scripts/bench-league-recheck.ps1 -Set all -Resume` and `scripts/league-unsupported-doc.ps1` after any such fix; a row that now produces numbers moves into `PerformanceLeague.md` automatically on the next `scripts/league-update-section.ps1`.')
Set-Content -Path $Out -Value $sb.ToString() -Encoding utf8
"wrote $Out : both=$($bothFail.Count) vulkan-only-fail=$($vulkanOnly.Count) cpu-only-fail=$($cpuOnlyFail.Count) timeouts=$($timeout.Count)"
